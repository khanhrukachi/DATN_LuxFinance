/// Translate built-in category identifiers; preserve names of user-created categories.
String chatCategoryLabel(BuildContext context, dynamic value, {
  List<Map<String, dynamic>> catalog = const [],
}) {
  final raw = value?.toString().trim() ?? '';
  if (raw.isEmpty) return AppLocalizations.of(context).translate('financial_chat_not_available');
  var candidate = raw;
  var fallbackName = raw;
  for (final category in catalog) {
    if ([category['id'], category['title'], category['display_name']]
        .any((v) => v?.toString().toLowerCase() == raw.toLowerCase())) {
      candidate = (category['title'] ?? category['id'] ?? raw).toString();
      fallbackName = (category['display_name'] ?? category['title'] ?? raw).toString();
      break;
    }
  }
  final key = _categoryAliases[candidate.toLowerCase()] ?? _categoryAliases[raw.toLowerCase()];
  return key == null ? fallbackName : AppLocalizations.of(context).translate(key);
}

